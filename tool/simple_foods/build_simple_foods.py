#!/usr/bin/env python3
"""Builds the simple-food list the app bundles from three files:

- tool/simple_foods/foods.tsv       hand-maintained: names, search words,
                                     portions and where the values come from
- assets/data/bls_4_0.tsv           the BLS (values for "bls:<code>" foods)
- tool/simple_foods/off_products.tsv Open Food Facts products (made by
                                     off_averages.py) for "off:<key>" foods

and writes, one file per licence:

- assets/data/simple_foods_bls.tsv  values from the BLS (CC BY 4.0)
- assets/data/simple_foods_off.tsv  medians of Open Food Facts products (ODbL)

Python 3.9+, standard library only, no internet. See README.md here.
"""

import statistics
import sys
from decimal import ROUND_HALF_UP, Decimal
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
FOODS = HERE / 'foods.tsv'
OFF_PRODUCTS = HERE / 'off_products.tsv'
BLS = ROOT / 'assets' / 'data' / 'bls_4_0.tsv'
OUT_BLS = ROOT / 'assets' / 'data' / 'simple_foods_bls.tsv'
OUT_OFF = ROOT / 'assets' / 'data' / 'simple_foods_off.tsv'

NUTRIENTS = ['kcal', 'fat', 'saturated_fat', 'carbs', 'sugars', 'fibre',
             'protein', 'salt']
COLUMNS = (['order', 'key', 'name_de', 'name_en', 'synonyms_de', 'synonyms_en']
           + NUTRIENTS
           + ['liquid', 'category', 'portion_g', 'portion_de', 'portion_en',
              'bls_code', 'off_products'])

HEADER_BLS = ('# Simple foods with values from the Bundeslebensmittelschlüssel (BLS) '
              '4.0, Max Rubner-Institut, CC BY 4.0 (see assets/data/README.md). '
              'Generated by tool/simple_foods/build_simple_foods.py - do not edit.')
HEADER_OFF = ('# Simple foods with typical values: medians of Open Food Facts products '
              'sold in Germany. Open Database License (ODbL) 1.0 (see '
              'assets/data/README.md). Generated by '
              'tool/simple_foods/build_simple_foods.py - do not edit.')


def fail(message):
    sys.exit(f'build_simple_foods.py: {message}')


def read_tsv(path):
    """Rows of a tab-separated file as dicts; lines starting with # skipped."""
    lines = [line.rstrip('\n').replace('\r', '')
             for line in path.read_text(encoding='utf-8').split('\n')]
    lines = [line for line in lines if line.strip() and not line.startswith('#')]
    header = lines[0].split('\t')
    rows = []
    for line in lines[1:]:
        cells = line.split('\t')
        if len(cells) != len(header):
            fail(f'{path.name}: wrong number of columns in "{line}"')
        rows.append(dict(zip(header, cells)))
    return rows


def round_half_up(value, places):
    quantum = Decimal(1).scaleb(-places)
    rounded = Decimal(str(value)).quantize(quantum, rounding=ROUND_HALF_UP)
    return format(rounded.normalize(), 'f')


def median_values(products):
    """The median of every value (fibre only from products that state it;
    unknown when fewer than half of them do). Rounded like the BLS file."""
    values = {}
    for column in NUTRIENTS:
        known = [float(p[column]) for p in products if p[column] != '']
        if not known or (column == 'fibre' and len(known) * 2 < len(products)):
            values[column] = ''
            continue
        places = 0 if column == 'kcal' else 2 if column == 'salt' else 1
        values[column] = round_half_up(statistics.median(known), places)
    return values


def check(row):
    """Stops on values a food cannot have (same limits as the app's form)."""
    def number(column):
        return None if row[column] == '' else float(row[column])

    kcal = number('kcal')
    if kcal is None or not 0 <= kcal <= 900:
        fail(f'{row["key"]}: kcal {row["kcal"]!r}')
    for column in NUTRIENTS[1:]:
        value = number(column)
        if value is not None and not 0 <= value <= 100:
            fail(f'{row["key"]}: {column} {value}')
    fat, saturated = number('fat'), number('saturated_fat')
    if fat is not None and saturated is not None and saturated > fat:
        fail(f'{row["key"]}: saturated fat {saturated} > fat {fat}')
    carbs, sugars = number('carbs'), number('sugars')
    if carbs is not None and sugars is not None and sugars > carbs:
        fail(f'{row["key"]}: sugars {sugars} > carbs {carbs}')
    if row['portion_g'] and not 0 < float(row['portion_g']) <= 1000:
        fail(f'{row["key"]}: portion {row["portion_g"]}')


def main():
    bls = {row['code']: row for row in read_tsv(BLS)}
    products = {}
    for product in read_tsv(OFF_PRODUCTS):
        products.setdefault(product['key'], []).append(product)

    out_bls, out_off = [], []
    seen_keys, seen_names, seen_codes = set(), set(), set()
    for order, food in enumerate(read_tsv(FOODS), start=1):
        key = food['key']
        for name, seen in ((key, seen_keys), (food['name_de'].lower(), seen_names),
                           ('en:' + food['name_en'].lower(), seen_names)):
            if name in seen:
                fail(f'{key}: "{name}" is used twice')
            seen.add(name)

        row = {'order': str(order), 'key': key}
        for column in ('name_de', 'name_en', 'synonyms_de', 'synonyms_en',
                       'portion_g', 'portion_de', 'portion_en'):
            row[column] = food[column]
        kind, _, ref = food['source'].partition(':')
        if kind == 'bls':
            source = bls.get(ref)
            if source is None:
                fail(f'{key}: no BLS food {ref}')
            if ref in seen_codes:
                fail(f'{key}: BLS code {ref} is used twice')
            seen_codes.add(ref)
            row.update({column: source[column] for column in NUTRIENTS})
            row['liquid'] = food['liquid'] or source['liquid']
            row['category'] = source['category']
            row['bls_code'] = ref
            row['off_products'] = ''
            out_bls.append(row)
        elif kind == 'off':
            used = products.get(ref)
            if not used:
                fail(f'{key}: no products for {ref} in {OFF_PRODUCTS.name} - '
                     'run off_averages.py')
            row.update(median_values(used))
            row['liquid'] = food['liquid'] or '0'
            row['category'] = ''
            row['bls_code'] = ''
            row['off_products'] = str(len(used))
            out_off.append(row)
        else:
            fail(f'{key}: unknown source {food["source"]!r}')
        check(row)

    for path, header, rows in ((OUT_BLS, HEADER_BLS, out_bls),
                               (OUT_OFF, HEADER_OFF, out_off)):
        lines = [header, '\t'.join(COLUMNS)]
        lines += ['\t'.join(row[column] for column in COLUMNS) for row in rows]
        path.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(f'{len(out_bls) + len(out_off)} simple foods: {len(out_bls)} from the BLS, '
          f'{len(out_off)} Open Food Facts medians')
    for row in out_off:
        print(f'  {row["key"]}: {row["off_products"]} products, {row["kcal"]} kcal')


if __name__ == '__main__':
    main()
